import fs from 'node:fs';
import path from 'node:path';

const dir = new URL('.', import.meta.url).pathname;
const evidence = JSON.parse(fs.readFileSync(path.join(dir, 'all-tools-official-pricing-evidence.json'), 'utf8'));

const tools = evidence.tools;
const VERIFIED_STATUS = new Set(['complete', 'partial', 'source-captured']);
const CHECKED_AT = '2026-08-06';

const verified = [];
const listedOnly = [];

for (const t of tools){
  const status = t.priceCheckStatus || 'source-unavailable';
  if (VERIFIED_STATUS.has(status) && t.sourcePriceUrl){
    const rec = {
      verificationLevel: 'pricing-verified',
    };
    if (t.startingPrice) rec.startingPrice = t.startingPrice;
    rec.pricingSourceUrl = t.sourcePriceUrl;
    rec.pricingCheckedAt = CHECKED_AT;
    rec.priceCheckStatus = status;
    if (t.priceCheckNote) rec.priceCheckNote = t.priceCheckNote;
    if (t.pricingPlans && t.pricingPlans.length) rec.pricingPlans = t.pricingPlans;
    verified.push({ slug: t.slug, name: t.name, rec });
  } else {
    listedOnly.push(t.slug);
  }
}

function emitTs(rec){
  const L = [];
  L.push('  ' + rec.slug + ': {');
  L.push("    verificationLevel: 'pricing-verified',");
  if (rec.rec.startingPrice) L.push(`    startingPrice: ${JSON.stringify(rec.rec.startingPrice)},`);
  if (rec.rec.pricingSourceUrl) L.push(`    pricingSourceUrl: ${JSON.stringify(rec.rec.pricingSourceUrl)},`);
  L.push(`    pricingCheckedAt: ${JSON.stringify(rec.rec.pricingCheckedAt)},`);
  L.push(`    priceCheckStatus: ${JSON.stringify(rec.rec.priceCheckStatus)},`);
  if (rec.rec.priceCheckNote) L.push(`    priceCheckNote: ${JSON.stringify(rec.rec.priceCheckNote)},`);
  if (rec.rec.pricingPlans){
    L.push('    pricingPlans: [');
    for (const p of rec.rec.pricingPlans){
      const f = p.features && p.features.length ? `, features: ${JSON.stringify(p.features)}` : '';
      L.push(`      { name: ${JSON.stringify(p.name)}, priceDisplay: ${JSON.stringify(p.priceDisplay)}, billing: ${JSON.stringify(p.billing)}${f} },`);
    }
    L.push('    ],');
  }
  L.push('  },');
  return L.join('\n');
}

let out = `import type { VerifiedRecord } from './tools';

/**
 * ════════════════════════════════════════════════════════════════════════
 *  THE EVIDENCE REGISTRY — the only place a trust claim can be granted.
 * ════════════════════════════════════════════════════════════════════════
 *
 * AUTO-EXPANDED (2026-08-06) from scripts/price-evidence/ — the official
 * pricing source crawl (all-tools-official-pricing-evidence.json). A tool is
 * 'pricing-verified' when its official pricing page was successfully captured
 * (priceCheckStatus = complete | partial | source-captured). Each record
 * carries the source URL, the date it was checked, a human note, and parsed
 * public plans when available.
 *
 * This file is GENERATED by scripts/price-evidence/build-verified.mjs.
 * Re-run it after a new crawl; hand-edit the override section at the bottom
 * only for cases the crawl cannot judge.
 */
export const VERIFIED_TOOLS: Record<string, VerifiedRecord> = {
`;
out += verified.map(emitTs).join('\n');
out += `};
`;
out += `// ${verified.length} pricing-verified · ${listedOnly.length} listed-only (official source not captured)\n`;
out += `// listed-only slugs: ${listedOnly.join(', ')}\n`;

fs.writeFileSync(path.join(dir, 'verified-tools.gen.ts'), out, 'utf8');
console.log(`Generated: ${verified.length} pricing-verified, ${listedOnly.length} listed-only`);

